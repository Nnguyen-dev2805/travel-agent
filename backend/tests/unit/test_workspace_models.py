"""Unit tests for R3 trip workspace value contracts.

These tests pin the workspace contract vocabulary defined by the approved R3
specification and ADR 0002. The contract layer must stay storage-agnostic and
route-agnostic: no FastAPI, SQLite, RAG, Chroma, model-provider, or evaluation
import may appear in it.
"""

from dataclasses import FrozenInstanceError, fields
from datetime import date, datetime, timedelta, timezone

import pytest

from backend.workspaces.models import (
    DESTINATION_SCOPE_MAX_LENGTH,
    TITLE_MAX_LENGTH,
    WORKSPACE_ID_PREFIX,
    DateWindow,
    PlanningStatus,
    RetentionState,
    TripWorkspace,
    WorkspaceCreate,
    WorkspaceListFilter,
    WorkspaceValidationError,
    generate_workspace_id,
    utc_now,
)


def _aware_now() -> datetime:
    return datetime(2026, 9, 3, 12, 0, 0, tzinfo=timezone.utc)


def _workspace(**overrides) -> TripWorkspace:
    """Build a valid TripWorkspace, overriding single fields per test."""
    payload = {
        "workspace_id": "tw_0123456789abcdef",
        "owner_user_id": "local-user",
        "title": "Da Nang family trip",
        "destination_scope": "Da Nang and Hoi An",
        "date_window": DateWindow(date(2026, 12, 20), date(2026, 12, 25)),
        "planning_status": PlanningStatus.IDEA,
        "retention_state": RetentionState.ACTIVE,
        "created_at": _aware_now(),
        "updated_at": _aware_now(),
    }
    payload.update(overrides)
    return TripWorkspace(**payload)


# 1. workspace_id is generated by storage/service, never accepted from input.


def test_workspace_create_has_no_workspace_id_field():
    field_names = {f.name for f in fields(WorkspaceCreate)}
    assert "workspace_id" not in field_names


def test_workspace_create_rejects_caller_supplied_workspace_id():
    with pytest.raises(TypeError):
        WorkspaceCreate(
            owner_user_id="local-user",
            title="Da Nang family trip",
            workspace_id="tw_caller_supplied",
        )


# 2. Generated IDs are strings prefixed with `tw_`.


def test_generate_workspace_id_uses_governed_prefix():
    workspace_id = generate_workspace_id()
    assert isinstance(workspace_id, str)
    assert workspace_id.startswith(WORKSPACE_ID_PREFIX)
    assert WORKSPACE_ID_PREFIX == "tw_"
    assert len(workspace_id) > len(WORKSPACE_ID_PREFIX)


def test_generate_workspace_id_is_unique_per_call():
    generated = {generate_workspace_id() for _ in range(50)}
    assert len(generated) == 50


# 3. owner_user_id and title are stripped and non-empty; title <= 120 chars.


def test_create_strips_owner_and_title():
    created = WorkspaceCreate(
        owner_user_id="  local-user  ",
        title="  Da Nang family trip  ",
    )
    assert created.owner_user_id == "local-user"
    assert created.title == "Da Nang family trip"


@pytest.mark.parametrize("blank", ["", "   ", "\t", "\n"])
def test_create_rejects_blank_owner(blank):
    with pytest.raises(WorkspaceValidationError):
        WorkspaceCreate(owner_user_id=blank, title="Da Nang family trip")


@pytest.mark.parametrize("blank", ["", "   ", "\t", "\n"])
def test_create_rejects_blank_title(blank):
    with pytest.raises(WorkspaceValidationError):
        WorkspaceCreate(owner_user_id="local-user", title=blank)


def test_title_accepts_maximum_length():
    created = WorkspaceCreate(
        owner_user_id="local-user",
        title="t" * TITLE_MAX_LENGTH,
    )
    assert len(created.title) == TITLE_MAX_LENGTH
    assert TITLE_MAX_LENGTH == 120


def test_title_rejects_over_maximum_length():
    with pytest.raises(WorkspaceValidationError):
        WorkspaceCreate(
            owner_user_id="local-user",
            title="t" * (TITLE_MAX_LENGTH + 1),
        )


def test_title_length_is_measured_after_stripping():
    padded = "  " + ("t" * TITLE_MAX_LENGTH) + "  "
    created = WorkspaceCreate(owner_user_id="local-user", title=padded)
    assert len(created.title) == TITLE_MAX_LENGTH


# 4. destination_scope is optional, stripped when present, <= 160 chars.


