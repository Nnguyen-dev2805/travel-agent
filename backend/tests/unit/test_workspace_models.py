# 5. Date window permits missing start/end but rejects end_date < start_date.


def test_date_window_allows_both_absent():
    window = DateWindow()
    assert window.start_date is None
    assert window.end_date is None


def test_date_window_allows_only_start():
    window = DateWindow(start_date=date(2026, 12, 20))
    assert window.start_date == date(2026, 12, 20)
    assert window.end_date is None


def test_date_window_allows_only_end():
    window = DateWindow(end_date=date(2026, 12, 25))
    assert window.start_date is None
    assert window.end_date == date(2026, 12, 25)


def test_date_window_allows_equal_start_and_end():
    same_day = date(2026, 12, 20)
    window = DateWindow(start_date=same_day, end_date=same_day)
    assert window.start_date == window.end_date


def test_date_window_rejects_end_before_start():
    with pytest.raises(WorkspaceValidationError):
        DateWindow(start_date=date(2026, 12, 25), end_date=date(2026, 12, 20))


def test_create_rejects_inverted_date_window():
    with pytest.raises(WorkspaceValidationError):
        WorkspaceCreate(
            owner_user_id="local-user",
            title="Trip",
            date_window=DateWindow(
                start_date=date(2026, 12, 25),
                end_date=date(2026, 12, 20),
            ),
        )


