def test_contract_module_imports_no_infrastructure():
    """The contract layer must not couple to storage, web, or RAG concerns.

    This asserts the real import graph rather than searching the source text, so
    a mention inside a docstring cannot pass or fail the check by accident.
    """
    import ast
    from pathlib import Path

    import backend.workspaces.models as models_module

    module_file = models_module.__file__
    assert module_file is not None
    tree = ast.parse(Path(module_file).read_text(encoding="utf-8"))

    imported: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            imported.update(alias.name for alias in node.names)
        elif isinstance(node, ast.ImportFrom) and node.module:
            imported.add(node.module)

    for forbidden in (
        "fastapi",
        "pydantic",
        "sqlite3",
        "chromadb",
        "openai",
        "sentence_transformers",
        "backend.rag",
        "backend.app",
        "backend.workspaces.repository",
        "backend.workspaces.sqlite_repository",
    ):
        offenders = [name for name in imported if name.startswith(forbidden)]
        assert not offenders, f"models.py must not import {forbidden}: {offenders}"
