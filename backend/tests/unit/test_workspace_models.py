# 9. Timestamps are timezone-aware UTC datetimes.


def test_utc_now_returns_timezone_aware_utc():
    now = utc_now()
    assert now.tzinfo is not None
    assert now.utcoffset() == timedelta(0)


def test_trip_workspace_rejects_naive_created_at():
    with pytest.raises(WorkspaceValidationError):
        _workspace(created_at=datetime(2026, 9, 3, 12, 0, 0))


def test_trip_workspace_rejects_naive_updated_at():
    with pytest.raises(WorkspaceValidationError):
        _workspace(updated_at=datetime(2026, 9, 3, 12, 0, 0))


def test_trip_workspace_normalizes_non_utc_offset_to_utc():
    plus_seven = timezone(timedelta(hours=7))
    workspace = _workspace(created_at=datetime(2026, 9, 3, 19, 0, 0, tzinfo=plus_seven))
    assert workspace.created_at.utcoffset() == timedelta(0)
    assert workspace.created_at == datetime(2026, 9, 3, 12, 0, 0, tzinfo=timezone.utc)


