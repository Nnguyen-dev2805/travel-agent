# 14. History query bounds.


def test_history_query_defaults_the_limit():
    query = MessageHistoryQuery(conversation_id="cv_example")
    assert query.limit == DEFAULT_HISTORY_LIMIT
    assert DEFAULT_HISTORY_LIMIT == 50
    assert query.after_message_id is None


@pytest.mark.parametrize("value", [1, 50, MAX_HISTORY_LIMIT])
def test_history_query_accepts_limits_inside_the_governed_range(value):
    assert MessageHistoryQuery(conversation_id="cv_example", limit=value).limit == value
    assert MAX_HISTORY_LIMIT == 200


@pytest.mark.parametrize("value", [0, -1, MAX_HISTORY_LIMIT + 1, 1.5, "50"])
def test_history_query_rejects_limits_outside_the_governed_range(value):
    with pytest.raises(ConversationValidationError):
        MessageHistoryQuery(conversation_id="cv_example", limit=value)


def test_history_query_strips_the_cursor_and_requires_a_conversation():
    query = MessageHistoryQuery(
        conversation_id="  cv_example  ", after_message_id="  ms_example  "
    )
    assert query.conversation_id == "cv_example"
    assert query.after_message_id == "ms_example"

    with pytest.raises(ConversationValidationError):
        MessageHistoryQuery(conversation_id="   ")


def test_history_query_treats_a_blank_cursor_as_absent():
    assert (
        MessageHistoryQuery(
            conversation_id="cv_example", after_message_id="  "
        ).after_message_id
        is None
    )


