"""Unit tests for the conversation and message value contracts.

These contracts are storage-agnostic and route-agnostic: the module under test
depends on the Python standard library only. Identity, ordering, and timestamps
are server-owned, so no caller-supplied value can set them.

No test here touches a database, a model provider, Chroma, or the network.
"""

import dataclasses
from datetime import datetime, timedelta, timezone

import pytest

import backend.conversations as conversations_package
from backend.conversations.models import (
    CONVERSATION_ID_PREFIX,
    DEFAULT_HISTORY_LIMIT,
    DEFAULT_MESSAGE_SOURCE,
    DEFAULT_RETENTION_STATE,
    DEFAULT_TRACE_VISIBILITY,
    MAX_HISTORY_LIMIT,
    MESSAGE_ID_PREFIX,
    PUBLIC_WRITABLE_ROLES,
    TITLE_MAX_LENGTH,
    Conversation,
    ConversationCreate,
    ConversationRetentionState,
    ConversationValidationError,
    Message,
    MessageDraft,
    MessageHistoryQuery,
    MessageRole,
    MessageSource,
    TraceVisibility,
    generate_conversation_id,
    generate_message_id,
    require_text,
    utc_now,
)

MOMENT = datetime(2026, 9, 4, 12, 0, 0, tzinfo=timezone.utc)


def _conversation(**overrides) -> Conversation:
    payload = {
        "conversation_id": generate_conversation_id(),
        "workspace_id": "tw_example",
        "title": "Da Nang food plan",
        "created_at": MOMENT,
        "updated_at": MOMENT,
    }
    payload.update(overrides)
    return Conversation(**payload)


def _draft(**overrides) -> MessageDraft:
    payload = {
        "conversation_id": "cv_example",
        "role": MessageRole.USER,
        "content": "Nên đi Đà Nẵng vào tháng mấy?",
        "created_at": MOMENT,
    }
    payload.update(overrides)
    return MessageDraft(**payload)


def _message(**overrides) -> Message:
    payload = {
        "message_id": generate_message_id(),
        "conversation_id": "cv_example",
        "sequence": 1,
        "role": MessageRole.USER,
        "content": "Nên đi Đà Nẵng vào tháng mấy?",
        "created_at": MOMENT,
    }
    payload.update(overrides)
    return Message(**payload)


def _field_names(contract: type) -> set[str]:
    return {item.name for item in dataclasses.fields(contract)}


# 1. Identity is generated by the module with governed prefixes.


def test_generated_identities_use_governed_prefixes():
    conversation_id = generate_conversation_id()
    message_id = generate_message_id()

    assert isinstance(conversation_id, str)
    assert isinstance(message_id, str)
    assert conversation_id.startswith(CONVERSATION_ID_PREFIX)
    assert message_id.startswith(MESSAGE_ID_PREFIX)
    assert CONVERSATION_ID_PREFIX == "cv_"
    assert MESSAGE_ID_PREFIX == "ms_"


def test_generated_identities_differ_across_calls():
    assert generate_conversation_id() != generate_conversation_id()
    assert generate_message_id() != generate_message_id()


def test_identity_prefix_is_enforced_on_rehydrated_records():
    with pytest.raises(ConversationValidationError):
        _conversation(conversation_id="tw_wrong_prefix")

    with pytest.raises(ConversationValidationError):
        _message(message_id="cv_wrong_prefix")


# 2. Identity and ordering cannot arrive from caller input.


def test_create_and_draft_contracts_expose_no_server_owned_fields():
    assert "conversation_id" not in _field_names(ConversationCreate)
    assert "message_id" not in _field_names(MessageDraft)
    assert "sequence" not in _field_names(MessageDraft)


# 3. `workspace_id` is stripped and required.


def test_workspace_id_is_stripped():
    assert (
        ConversationCreate(workspace_id="  tw_example  ").workspace_id == "tw_example"
    )
    assert _conversation(workspace_id="  tw_example  ").workspace_id == "tw_example"


@pytest.mark.parametrize("value", ["", "   ", None, 7])
def test_workspace_id_is_required(value):
    with pytest.raises(ConversationValidationError):
        ConversationCreate(workspace_id=value)


# 4 and 5. `title` is optional, stripped, bounded, and blank means absent.


def test_title_is_optional_and_stripped():
    assert ConversationCreate(workspace_id="tw_example").title is None
    assert (
        ConversationCreate(workspace_id="tw_example", title="  Da Nang  ").title
        == "Da Nang"
    )


@pytest.mark.parametrize("value", ["", "   ", "\n\t "])
def test_blank_title_normalizes_to_absent_rather_than_raising(value):
    assert ConversationCreate(workspace_id="tw_example", title=value).title is None
    assert _conversation(title=value).title is None


def test_title_at_the_maximum_length_is_accepted():
    exact = "t" * TITLE_MAX_LENGTH
    assert TITLE_MAX_LENGTH == 120
    assert ConversationCreate(workspace_id="tw_example", title=exact).title == exact


def test_title_over_the_maximum_length_raises():
    with pytest.raises(ConversationValidationError):
        ConversationCreate(
            workspace_id="tw_example", title="t" * (TITLE_MAX_LENGTH + 1)
        )

    with pytest.raises(ConversationValidationError):
        _conversation(title="t" * (TITLE_MAX_LENGTH + 1))


def test_non_string_title_raises():
    with pytest.raises(ConversationValidationError):
        ConversationCreate(workspace_id="tw_example", title=42)


# 6 and 7. `content` is required, and deliberately unbounded.


@pytest.mark.parametrize("value", ["", "   ", "\n", None, 7])
def test_content_is_required_and_non_blank(value):
    with pytest.raises(ConversationValidationError):
        _draft(content=value)

    with pytest.raises(ConversationValidationError):
        _message(content=value)


def test_content_is_stripped():
    assert _draft(content="  xin chào  ").content == "xin chào"


def test_content_has_no_maximum_length():
    """A deliberate departure from the R3 bounded-text rule, recorded in the spec.

    The chat route already accepts an unbounded `message`, so a storage limit
    would turn requests that succeed today into failures once a conversation is
    bound. Request size limiting belongs at the API boundary.
    """
    long_content = "a" * 100_000
    assert len(_draft(content=long_content).content) == 100_000
    assert len(_message(content=long_content).content) == 100_000


