def test_require_text_is_shared_by_both_value_objects():
    assert require_text("  cv_example  ", "conversation_id") == "cv_example"

    with pytest.raises(ConversationValidationError):
        require_text("   ", "conversation_id")


def test_contracts_are_frozen_so_records_cannot_drift_after_validation():
    conversation = _conversation()
    message = _message()

    with pytest.raises(dataclasses.FrozenInstanceError):
        conversation.title = "changed"

    with pytest.raises(dataclasses.FrozenInstanceError):
        message.sequence = 99


def test_contract_module_imports_only_the_standard_library():
    """The contract layer must stay storage-agnostic and route-agnostic."""
    import sys

    import backend.conversations.models as models_module

    forbidden = ("fastapi", "pydantic", "sqlite3", "chromadb", "backend.rag")
    source_globals = vars(models_module)
    imported = {
        value.__name__
        for value in source_globals.values()
        if isinstance(value, type(sys))
    }
    assert not any(
        name.startswith(prefix) for name in imported for prefix in forbidden
    ), f"contract module imported a forbidden dependency: {imported}"
