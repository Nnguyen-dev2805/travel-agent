# 12. Timestamps must be timezone-aware and are normalized to UTC.


def test_timestamps_are_normalized_to_utc():
    offset = timezone(timedelta(hours=7))
    local = datetime(2026, 9, 4, 19, 0, 0, tzinfo=offset)

    conversation = _conversation(created_at=local, updated_at=local)
    assert conversation.created_at.utcoffset() == timedelta(0)
    assert conversation.created_at == local
    assert _message(created_at=local).created_at.utcoffset() == timedelta(0)
    assert _draft(created_at=local).created_at.utcoffset() == timedelta(0)


@pytest.mark.parametrize("value", [datetime(2026, 9, 4, 12, 0, 0), "2026-09-04", None])
def test_naive_or_non_datetime_timestamps_raise(value):
    with pytest.raises(ConversationValidationError):
        _conversation(created_at=value)

    with pytest.raises(ConversationValidationError):
        _conversation(updated_at=value)

    with pytest.raises(ConversationValidationError):
        _message(created_at=value)

    with pytest.raises(ConversationValidationError):
        _draft(created_at=value)


def test_utc_now_returns_timezone_aware_utc():
    moment = utc_now()
    assert moment.tzinfo is not None
    assert moment.utcoffset() == timedelta(0)


