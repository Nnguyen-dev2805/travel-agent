def test_unknown_enum_values_are_rejected():
    with pytest.raises(MemoryValidationError):
        _candidate(proposed_scope="galaxy")
    with pytest.raises(MemoryValidationError):
        _candidate(status="pending")
    with pytest.raises(MemoryValidationError):
        _run(trigger="automatic")


def test_raw_string_values_coerce_to_enums():
    candidate = _candidate(proposed_scope="user", status="accepted")
    assert candidate.proposed_scope is MemoryScope.USER
    assert candidate.status is MemoryCandidateStatus.ACCEPTED


# 6. Run counters are consistent, including invalid_count.


def test_run_counts_must_add_up():
    run = _run(
        candidate_count=4,
        accepted_count=1,
        rejected_count=1,
        needs_user_action_count=1,
        invalid_count=1,
    )
    assert run.candidate_count == 4


def test_run_counts_reject_mismatch_and_negatives():
    with pytest.raises(MemoryValidationError):
        _run(
            candidate_count=2,
            accepted_count=1,
            rejected_count=0,
            needs_user_action_count=0,
            invalid_count=0,
        )
    with pytest.raises(MemoryValidationError):
        _run(
            candidate_count=0,
            accepted_count=0,
            rejected_count=0,
            needs_user_action_count=0,
            invalid_count=-1,
        )


# 7. Ordering facts needed by later milestones.


def test_sequence_starts_at_one_and_rejects_zero():
    assert _source_message(sequence=1).sequence == 1
    with pytest.raises(MemoryValidationError):
        _source_message(sequence=0)
    with pytest.raises(MemoryValidationError):
        _candidate(source_sequence=0)


def test_draft_starts_unevaluated():
    draft = _draft()
    assert draft.status is None
    assert draft.reason is None


